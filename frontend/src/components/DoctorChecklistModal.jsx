import { useEffect, useState } from 'react';
import { t } from '../i18n/translations';

export default function DoctorChecklistModal({ record, open, onClose, lang = 'zh-TW' }) {
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (!open) return undefined;
    const previous = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    return () => {
      document.body.style.overflow = previous;
    };
  }, [open]);

  useEffect(() => {
    if (!open) setCopied(false);
  }, [open]);

  if (!record || !open) return null;

  const checklist = record.doctor_checklist;
  const copyText = async () => {
    const lines =
      lang === 'en'
        ? [
            `[${record.gene.symbol} · ${record.gene.chinese_name}] Outpatient Doctor Checklist`,
            `Recommended Specialty: ${checklist.specialty}`,
            '',
            ...checklist.questions.map((question, index) => `${index + 1}. ${question}`),
            '',
            '— Generated by DecodeGene for clinical consultation reference.',
          ]
        : [
            `【${record.gene.symbol} · ${record.gene.chinese_name}】門診提問清單`,
            `建議科別：${checklist.specialty}`,
            '',
            ...checklist.questions.map((question, index) => `${index + 1}. ${question}`),
            '',
            '—— 由 DecodeGene 解碼基因產生，僅供就醫溝通參考。',
          ];
    const text = lines.join('\n');
    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(text);
      } else {
        const area = document.createElement('textarea');
        area.value = text;
        document.body.appendChild(area);
        area.select();
        document.execCommand('copy');
        document.body.removeChild(area);
      }
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  };

  return (
    <div className="modal-backdrop" role="presentation" onClick={onClose}>
      <div
        className="modal"
        role="dialog"
        aria-modal="true"
        aria-labelledby="checklist-title"
        onClick={(event) => event.stopPropagation()}
      >
        <div className="modal-head">
          <div>
            <div className="card-eyebrow">{t(lang, 'modalEyebrow')}</div>
            <h2 id="checklist-title">
              {record.gene.symbol} · {record.gene.chinese_name}
            </h2>
            <p className="modal-specialty">
              {t(lang, 'checklistSpecialty')}
              {checklist.specialty}
            </p>
          </div>
          <button type="button" className="icon-button" onClick={onClose} aria-label="Close">
            ✕
          </button>
        </div>

        <ol className="checklist-list">
          {checklist.questions.map((question) => (
            <li key={question}>{question}</li>
          ))}
        </ol>

        <div className="modal-actions">
          <button type="button" className="primary-button" onClick={copyText}>
            {copied ? t(lang, 'modalCopiedBtn') : t(lang, 'modalCopyBtn')}
          </button>
          <button type="button" className="ghost-button" onClick={() => window.print()}>
            {t(lang, 'modalPrintBtn')}
          </button>
        </div>

        <p className="modal-note">{t(lang, 'modalNote')}</p>
      </div>
    </div>
  );
}

